"""Generate the level circular 202-pixel C64U renderer and its timing record.

The two guard pixels are outside the 200-pixel viewport. Padding after exit
jumps is unreachable and prevents taken branches acquiring page-cross cycles.
"""
from pathlib import Path
import json

ROOT=Path(__file__).resolve().parents[1]

def generate():
    lines=['; Generated by tools/generate_tilt.py; do not edit.',
           '.p2align 8','.globl havoc_tilt_entries','havoc_tilt_entries:',
           '.short '+','.join(f'.Lcolumn_{i}' for i in range(128)),
           '.globl havoc_tilt_pixels','havoc_tilt_pixels:']
    offset=0;starts=[];padding=[]
    for column in range(128):
        starts.append(offset)
        lines += [f'.Lcolumn_{column}:',f'    ldx ${0x4000+column*256:04x},y',
                  '    stx $d020','    .byte $ce, $ef, $00 ; DEC absolute: six cycles',
                  f'.Lstep_{column}:','    nop','    lda havoc_raster_nibbles,x',
                  '    sta $d020','    lda $ef']
        if column==127:
            assert (offset+20)//256==(offset+23)//256
            lines += ['    beq .Llast_exit','    jmp .Lcolumn_0',
                      '.Llast_exit:','    nop','.Lpixel_end:','    nop',
                      '    lda #0','    sta $d020','    rts']
            offset+=33
        else:
            nop=(column+1)%4!=3
            for pad in range(8):
                next_start=offset+23+pad+int(nop)
                if ((offset+20)//256==(offset+23+pad)//256 and
                    (next_start+20)//256==(next_start+23)//256):
                    break
            else:raise AssertionError((column,offset))
            lines += [f'    bne .Lnext_{column}','    jmp .Lpixel_end']
            if pad:lines += ['    .byte '+','.join('$ea' for _ in range(pad))+' ; unreachable alignment']
            lines += [f'.Lnext_{column}:']
            if nop:lines += ['    nop']
            padding.append(pad);offset=next_start
    (ROOT/'target-c64/asm/tilt_pixels.inc').write_text('\n'.join(lines)+'\n',encoding='utf-8')
    (ROOT/'target-c64/tilt-timing.json').write_text(json.dumps({
        'hardware_measured':False,'columns':128,'pairs_per_line':101,
        'guard_pixels':2,'entry_offsets':starts,'unreachable_padding_bytes':sum(padding),
        'kernel_bytes':offset,'tables_in_alignment_gaps_bytes':0,
        'angle_tables_bytes':0,'static_level_renderer':True,
        'row_setup_cycles_including_jsr':172,
        'preamble_even_delay13':549,'preamble_odd_delay13':533,
        'phase_correction_cycles':[0]*8,'k_range':[0,0],
        'prepare_cycles':36,
    },indent=2)+'\n',encoding='utf-8')
    print(f'Circular kernel: {offset} bytes, {sum(padding)} unreachable alignment bytes')

if __name__=='__main__':generate()
