"""Build the hardware-gate fixture, not the final four-volume soundtrack.

Only standard-library Python is required. The REU contains compressed DLT5,
never a predecoded recording. The C64 must generate every played PCM sample.
"""
from pathlib import Path
import hashlib
import json
import struct

ROOT = Path(__file__).resolve().parents[1]


def main():
    fixture = ROOT / 'target/music/diagnostic/hammond-rocker.dlt'
    blob = fixture.read_bytes()
    meta = json.loads(fixture.with_suffix('.json').read_text())
    assert blob[:4] == b'DLT5' and struct.unpack_from('<I', blob, 4)[0] == 32000
    assert blob[20:22] == bytes([3, 2])
    assert hashlib.sha256(blob).hexdigest() == meta['asset_sha256']
    assert len(blob) == meta['asset_bytes']
    assert len(blob) < 0xf000, 'diagnostic clip overlaps the picture'
    out = ROOT / 'dist/prototype'
    out.mkdir(parents=True, exist_ok=True)
    image = bytearray(0x1000000)
    image[:8] = b'HVMPROT1'
    image[0x1000:0x1000 + len(blob)] = blob
    cache = ROOT / 'target/art/lowland-approach.cache.bin'
    if cache.exists():
        picture = cache.read_bytes()
        assert len(picture) == 32768
        image[0x10000:0x18000] = picture
        image[8] = 1
    for i in range(16384):
        image[0x200000+i] = (i ^ (i >> 8) ^ 0x5a) & 255
    reu = out / 'havocmd-prototype.reu'
    reu.write_bytes(image)
    header = ROOT / 'target-c64/include/prototype_assets.h'
    header.parent.mkdir(parents=True, exist_ok=True)
    header.write_text(
        '/* Generated by tools/prepare-prototype.py; compressed diagnostic audio. */\n'
        '#ifndef HAVOC_PROTOTYPE_ASSETS_H\n#define HAVOC_PROTOTYPE_ASSETS_H\n'
        '#define AUDIO_REU 0x1000UL\n'
        f'#define AUDIO_FRAMES {meta["sample_count"]}UL\n'
        f'#define AUDIO_BOOKS {meta["codebook_count"]}u\n'
        f'#define AUDIO_STREAM_OFFSET {meta["stream_offset"]}UL\n'
        f'#define AUDIO_SHORT_SEGMENT {meta["samples_per_segment"]}u\n'
        f'#define AUDIO_LONG_SEGMENTS {meta["long_segment_count"]}u\n'
        '#endif\n')
    report = {'prototype': True, 'hardware_measured': False, 'passed': False,
              'audio_profile': 'stereo32k3', 'frames': meta['sample_count'],
              'audio_sha256': meta['asset_sha256'],
              'reu_sha256': hashlib.sha256(image).hexdigest(),
              'picture_present': bool(image[8])}
    (out / 'build-report.json').write_text(json.dumps(report, indent=2) + '\n')
    print(f'Prepared {reu.name}: {len(blob)} compressed audio bytes; physical timing not yet measured')


if __name__ == '__main__':
    main()
