"""Emit straight-line 6502 border stores and their reviewable cycle schedule.

No upstream renderer source is incorporated. Timing uses the published Ultimate
63-turbo-cycles/PHI2 observation; actual NTSC beam alignment remains a hardware
calibration, independently of these instruction counts.
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
PAIRS = 100
WORK_CYCLES = 256


def generate(phase):
    name = "odd" if phase else "even"
    lines = [f"; {name}: 200 logical pixels, each two physical VIC dots.",
             ".p2align 8", f".globl havoc_raster_{name}_line",
             f"havoc_raster_{name}_line:", f".L{name}_line:"]
    source_operands = []
    # One shortened fetch per eight logical pixels makes 126 cycles/16 dots.
    for pair in range(3, PAIRS, 4):
        col = pair + phase
        lines += [f".L{name}_patch_{pair}:", "    lda $4000,y",
                  f"    sta .L{name}_fetch_{pair}+1"]
    lines += ["    tya", "    pha", "    jsr havoc_raster_work", "    pla", "    tay",
              f".L{name}_delay:", "    ldx #13", f".L{name}_delay_loop:",
              "    dex", f"    bne .L{name}_delay_loop", f".L{name}_pad:",
              "    nop", "    nop", "    nop", f".L{name}_pad_end:"]
    if phase:
        lines += [".Lodd_first:", "    ldx $4000,y"]
        source_operands.append((0, ".Lodd_first+2"))
    else:
        # Match the odd phase's initial indexed fetch without touching X/Y.
        lines += ["    bit havoc_raster_nibbles"]
    stores = []
    cycles = 0
    for pair in range(PAIRS):
        short = pair % 4 == 3
        col = pair + phase
        fetch_label = f".L{name}_fetch_{pair}"
        fetch = [fetch_label + ":", "    ldx #0" if short else "    ldx $4000,y"]
        source_operands.append((col, f".L{name}_patch_{pair}+2" if short else fetch_label + "+2"))
        if phase:
            lines += ["    lda havoc_raster_nibbles,x", "    sta $d020"]
            cycles += 8
            stores.append({"pixel": pair * 2, "column": pair, "nibble": "high", "cycle": cycles})
            lines += ["    nop"] * 4
            cycles += 8
            lines += fetch + ["    stx $d020"]
            cycles += (2 if short else 4) + 4
            stores.append({"pixel": pair * 2 + 1, "column": col, "nibble": "low", "cycle": cycles})
        else:
            lines += fetch + ["    stx $d020"]
            cycles += (2 if short else 4) + 4
            stores.append({"pixel": pair * 2, "column": col, "nibble": "low", "cycle": cycles})
            lines += ["    nop"] * 4
            cycles += 8
            lines += ["    lda havoc_raster_nibbles,x", "    sta $d020"]
            cycles += 8
            stores.append({"pixel": pair * 2 + 1, "column": col, "nibble": "high", "cycle": cycles})
        lines += ["    nop"] * 4
        cycles += 8
    # Last color must stay on screen for a complete two-dot pixel.
    lines += ["    nop", "    lda #0", "    sta $d020", "    rts"]
    black_cycle = cycles + 8
    assert cycles == 3150
    assert black_cycle - stores[0]["cycle"] == 3150
    source_operands.sort()
    assert [col for col, _ in source_operands] == list(range(100 + phase))
    lines += [f".L{name}_operands:"]
    lines += ["    .short " + ", ".join(ref for _, ref in source_operands)]
    return lines, {"phase": name, "pixel_cycles": cycles, "black_store_cycle": black_cycle,
                   "stores": stores}


def main():
    generated = ["; Generated by target-c64/tools/generate_raster.py. Do not hand-edit."]
    schedules = []
    for phase in (0, 1):
        code, trace = generate(phase)
        generated += code
        schedules.append(trace)
    (ROOT / "asm" / "raster_pixels.inc").write_text("\n".join(generated) + "\n", encoding="utf-8")
    trace = {
        "assumption": "63 CPU cycles per VIC PHI2 at the 64 MHz setting; hardware verification required",
        "logical_width": 200, "physical_dots": 400, "rows": 240,
        "work_cycles_including_rts": WORK_CYCLES,
        "preamble_cycles_at_delay_13": 549,
        "line_call_cycles_at_delay_13": 3719,
        "phase_schedules": schedules,
    }
    (ROOT / "raster-timing.json").write_text(json.dumps(trace, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
